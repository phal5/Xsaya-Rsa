/// <summary>
/// 스킬이 선택되기 위한 추가 조건. 쿨다운·사거리는 스킬이 이미 보므로 그 밖의 것만 적는다.
///
/// 스킬의 Condition Script 칸에 이 인터페이스를 구현한 스크립트를 꽂으면 그 조건이 붙는다.
/// 비워두면 조건 없음이다. FSM이 초기 상태를 받는 방식과 같다 —
/// 인스펙터는 스크립트를 받고, 빌드를 위해 클래스 이름을 문자열로 저장한다.
///
/// MonoBehaviour가 아니라 순수 클래스다. 조건은 상태를 갖지 않고 물어보면 답만 한다.
/// 그래서 인스펙터 파라미터를 달 수 없다 — 값이 다르면 스크립트를 하나 더 만든다.
///
/// 구현은 <b>파일명과 클래스명을 맞춰야</b> 인스펙터에 꽂힌다. HealthBelowHalf를 참고.
/// </summary>
public interface ISkillCondition
{
    bool Met(BossManager boss);
}
